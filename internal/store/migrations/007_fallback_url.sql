-- Запасной адрес опроса.
--
-- У сервиса, найденного в кластере, адресов на самом деле два: backend-Service
-- внутри кластера и публичный хост из правила Ingress. Опрашивается основной
-- (по умолчанию внутренний — это прямой вызов, который не уходит на внешний
-- балансировщик), но именно он ломается первым: NetworkPolicy между
-- namespace, переименованный Service, порт, доступный только ingress-
-- контроллеру. Во всех этих случаях публичный хост продолжает отвечать, и
-- считать сервис недоступным неправильно.
--
-- fallback_url хранит второй адрес, using_fallback — какой из них сработал в
-- прошлый раз, чтобы сервис, постоянно живущий за публичным хостом, не платил
-- неудачной попыткой на каждом опросе.
ALTER TABLE services ADD COLUMN IF NOT EXISTS fallback_url   TEXT;
ALTER TABLE services ADD COLUMN IF NOT EXISTS using_fallback BOOLEAN NOT NULL DEFAULT FALSE;

