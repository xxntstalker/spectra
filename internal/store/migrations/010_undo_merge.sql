-- Отмена схлопывания дублей.
--
-- Схлопывание пряталo записи, деля их на «настоящую» и «лишние». Признак, по
-- которому выбиралась настоящая, включал число ревизий — а оно растёт. В
-- результате победитель переворачивался сам собой, без единого изменения в
-- кластере: сегодня по адресу видна одна запись, завтра другая. Человек,
-- вписавший адрес спеки, назавтра не находил его на месте — потому что смотрел
-- уже на соседнюю запись.
--
-- Надёжного признака «какой backend за этим адресом настоящий» у портала нет,
-- и придумывать его не следовало. Теперь совпадение публичного адреса — это
-- пометка «возможно, дубль» рядом с обеими записями и объяснение, почему так
-- считается. Решает человек, кнопкой «спрятать».
--
-- Возвращаются ровно те записи, которые спрятал портал: superseded_by
-- проставлен только им. present всё равно перевычисляется ближайшим
-- сканированием кластера, так что восстановление здесь — на случай, если
-- сканирование ещё не прошло.
UPDATE services
SET present       = TRUE,
    auto_probe    = TRUE,
    superseded_by = NULL,
    updated_at    = now()
WHERE superseded_by IS NOT NULL;

DROP INDEX IF EXISTS idx_services_superseded;

-- Колонка superseded_by остаётся неиспользованной намеренно: на неё ссылается
-- предыдущая версия приложения, и её удаление сделало бы откат невозможным.
-- Убрать отдельной миграцией, когда откат перестанет быть нужен.
--
-- auto_probe восстанавливается всем: отличить «выключил портал при слиянии» от
-- «спека не нашлась ещё раньше» нельзя. У кого спеки нет, первый же опрос
-- выключит его обратно — ценой одного лишнего перебора путей.
