-- Спецификация хранится как текст, а не как jsonb.
--
-- Внутрь спеки мы никогда не запрашиваем — она только кладётся и отдаётся
-- целиком. Зато jsonb делает две вещи, которых здесь не надо:
--
--   1. Переформатирует содержимое, так что байты на выходе не равны байтам
--      на входе.
--   2. Отвергает u0000 в строках. Спека, где такое экранирование попало в
--      пример значения, не записалась бы вовсе — с невнятной ошибкой и без
--      ревизии у сервиса.
--
-- Текст решает обе: точный обход туда-обратно и никаких сюрпризов на чужих
-- данных, которые мы не контролируем.
ALTER TABLE spec_versions ALTER COLUMN spec TYPE TEXT;
